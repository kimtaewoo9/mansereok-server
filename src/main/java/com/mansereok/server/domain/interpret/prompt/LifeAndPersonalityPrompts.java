	static String createPersonalityAnalysisPrompt(String name,
		ManseryeokCalculationResponse response) {
		StringBuilder prompt = new StringBuilder();
		ManseryeokCalculationResponse.SajuInfo saju = response.getSaju();
		ManseryeokCalculationResponse.InputInfo input = response.getInput();

		// 1. '혜안' 공통 페르소나 주입
		PromptSections.appendHyeanPersonaHeader(prompt);

		// 2. 분석 대상자 정보 주입
		prompt.append("""
			### 5. 분석 대상자 상세 정보 (Data for Analysis) ###
			""");
		SajuProfileSections.appendPersonDetailInfo(prompt, name, response);

		SajuKeywordSections.appendKeywords(prompt, response);

		// 3. 분석 요청
		prompt.append("""

			### 6. [성격 심층 분석] 요청 ###
			혜안 선생님, 위 데이터를 바탕으로 %s님의 '성격 서사'를 한 편의 글로 완성해주세요.
			이 분석은 유료 상품입니다. MBTI 설명처럼 누구에게나 맞는 말은 돈값을 못 합니다. 모든 판단은 위 데이터의 실제 글자에서 출발하고, 읽는 사람이 '아 맞아 나 그래' 하고 고개를 끄덕일 수준의 구체성이 기준입니다.

			"""
			.formatted(name));

		prompt.append("""
			**[구성의 자유]** 아래 `##` 주제들은 재료입니다. 순서를 바꾸거나 묶어도 되고, 제목을 이 사주에 맞게 다시 지어도 됩니다(`##`로 시작만 유지하세요). 이 사주의 성격을 관통하는 중심 테마 하나를 먼저 잡고, 각 섹션이 그 테마의 다른 얼굴이 되도록 엮으세요. 다음 섹션 예고로 궁금증을 이어가도 좋습니다.

			""");

		prompt.append("""
			**[분량/문단 규칙]** fullAnalysis 전체 4,000자 이상, 각 주제당 500~700자. 한 문단은 6~7줄 이내, 문단 경계는 줄바꿈 두 번만 사용.

			""");

		prompt.append("""
			**[문체 기준 - 호흡과 톤만 재현, 문장 복사 금지]**
			"처음 보는 사람들에게는 차분하고 예의 바르다는 말을 자주 들을 거예요. 그런데 정작 속에서는 '이건 왜 이렇게 하지?' 하는 생각이 쉬지 않고 돌아갑니다. 겉과 속의 온도차가 꽤 있는 구조인데, 왜 그런지 사주를 따라가면서 하나씩 풀어볼게요."

			""");

		prompt.append("""
			--- [분석 시작] ---
			"%s님은 %s %s에 태어나신, [일간(%s) 자연물 비유]와 같은 기운을 지니셨네요." 로 시작해주세요.

			"""
			.formatted(
				name,
				input.getSolarDate(),
				input.getSolarTime(),
				saju.getDaySky().getKorean() + saju.getDaySky().getFiveCircle()));

		prompt.append("""
			## 핵심 성격 키워드와 그 근원
			이 사람을 가장 잘 나타내는 성격 키워드 3가지를 선정하고, 각 키워드가 어떤 사주 요소(일간, 월지, 십성 등)에서 비롯됐는지 근거를 밝히세요.
			키워드마다 그 성격이 실제로 드러나는 현실 장면(일할 때, 사람들 사이에서, 혼자 있을 때)을 하나씩 붙여서, 추상적 형용사 나열이 되지 않게 하세요.

			""");

		prompt.append("""
			## 겉모습(페르소나) vs 진짜 내면
			사회적으로 보이는 모습(천간 십성)과 실제 내면(지지, 지장간)의 차이를 분석하세요.
			차이가 크다면 왜 그런 구조인지, 어떤 상황에서 숨겨둔 내면이 튀어나오는지 구체적 장면으로 묘사하세요.
			겉과 속이 비슷한 구조라면 억지로 차이를 만들지 말고, 그 일관성이 강점이자 약점이 되는 지점을 짚어주세요.

			""");

		prompt.append("""
			## 사고방식, 가치관, 그리고 강점과 약점
			십성 분포를 근거로 주요 사고 패턴(논리/직관, 감성/이성)과 인생에서 중요하게 여기는 가치(명예/재물/안정/자유)를 판단하세요.
			강점 3가지와 약점 2가지를 명확히 제시하되, 각각 어떤 글자 때문인지 근거를 붙이세요.
			약점은 부드럽게 포장하지 말고, 이 약점이 반복시키는 실수 패턴까지 솔직하게 보여주세요.

			""");

		prompt.append("""
			## 인간관계 스타일 (관계 유형별)
			친구, 직장 동료(상사/부하), 연인, 가족 각각에서 이 사람이 관계 맺는 방식이 어떻게 달라지는지 분석하세요.
			각 관계에서 반복되기 쉬운 갈등 패턴을 사주 근거(충/형, 비겁/관성 상태 등)와 함께 짚고, 이 사주에 맞는 해결 방식을 조언하세요.
			잘 맞는 사람 유형과 부딪히기 쉬운 사람 유형을 구체적으로 묘사하세요.

			""");

		prompt.append("""
			## 자기 성장과 행복을 위한 조언
			앞의 분석을 종합해, 이 사람이 삶의 만족도를 높이려면 무엇에 집중해야 하는지 우선순위 하나를 명확히 제시하세요.
			'자존감을 높이세요' 같은 일반론 대신, 이 사주 구조라서 필요한 구체적 방향(예: 출력 연습, 거리 두기, 루틴 고정)을 담아 따뜻하게 마무리하세요.

			""");

		PromptSections.appendSajuJsonResponseFormat(prompt);

		return prompt.toString();
	}

