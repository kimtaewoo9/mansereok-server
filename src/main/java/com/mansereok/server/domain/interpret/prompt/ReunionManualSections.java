package com.mansereok.server.domain.interpret.prompt;


/**
 * 재회운 프롬프트의 뒷부분. 제3장(재회 가능성·골든타임)부터 제4장(실전 매뉴얼)과
 * 제출 전 체크리스트까지를 맡는다. 한 메서드가 700행에 가까워 장 단위로 갈랐다.
 */
final class ReunionManualSections {

	private ReunionManualSections() {
	}

	static void appendReunionManual(StringBuilder prompt, String person1Name,
		String person2Name, String todayDate) {
		// ==========================================
		// 제3장: 재회 가능성 및 타이밍
		// ==========================================
		prompt.append("""
			==================================================
			⏰ 제3장: 재회 가능성 및 골든타임
			==================================================

			""");

		prompt.append("""
			**재회 가능성을 종합 평가하세요**

			""");

		prompt.append("""
			사주 궁합, 현재 운세, 성격 조화도를 종합해서 평가하고,
			별점(★)으로 재회 가능성을 표시하세요.

			""");

		prompt.append(
			String.format("%s님과 %s님의 재회 가능성: ★★★☆☆ (이런 식으로)\n\n", person1Name, person2Name));

		prompt.append("""
			별점 기준:
			★★★★★ - 매우 높음: 천생연분, 시간이 약. 반드시 다시 만나게 되어 있음
			★★★★☆ - 높음: 노력하면 충분히 가능. 타이밍만 잘 맞추면 됨
			★★★☆☆ - 보통: 50대50. 당신의 전략과 상대방 상황에 따라 달라짐
			★★☆☆☆ - 낮음: 쉽지 않음. 근본적인 문제를 해결해야 가능
			★☆☆☆☆ - 매우 낮음: 거의 불가능. 새로운 인연을 찾는 게 나음

			""");

		prompt.append("""
			**근거를 구체적으로 제시하세요**
			1. 사주 궁합 점수 (100점 만점)
			2. 헤어진 이유의 해결 가능성 (높음/보통/낮음)
			3. 현재 두 사람의 운세 싱크로율 (좋음/보통/나쁨)

			""");

		prompt.append("""
			**솔직한 한마디를 추가하세요**

			""");

		prompt.append("""
			재회 가능성이 낮으면:
			솔직히 말씀드리면, 이 인연은 여기서 끝내는 게 나을 수 있습니다.
			억지로 재회해도 똑같은 이유로 또 헤어질 확률이 높아요.
			차라리 이 경험을 교훈 삼아 더 잘 맞는 사람을 만나시는 걸 추천합니다.

			""");

		prompt.append("""
			재회 가능성이 높으면:
			좋은 소식입니다. 두 분은 충분히 다시 만날 수 있어요.
			하지만 타이밍을 놓치면 기회가 영영 사라질 수 있으니,
			아래 내용을 반드시 숙지하세요.

			""");

		prompt.append("""
			**재회 골든타임 3개를 제시하세요** ⚠️ 절대 과거 날짜 금지

			""");

		prompt.append("현재 ").append(todayDate).append(" 이후의 미래 시점만 제시해야 합니다.\n\n");

		prompt.append("""
			두 분 모두의 사주를 분석한 결과, 재회에 유리한 시기는 다음과 같습니다:

			""");

		prompt.append("""
			**1순위 타이밍** - 202X년 X월
			왜 이 시기가 최적인지 300자 이상 구체적으로 설명하세요:
			- 두 사람 모두 애정운이 동시에 상승하는지
			- 특히 상대방의 감정선이 부드러워지는지
			- 사주상 합(合)이 형성되어 화해 분위기가 조성되는지
			사주 근거를 들어 설명하세요.

			""");

		prompt.append("""
			**2순위 타이밍** - 202X년 X월
			1순위를 놓쳤다면 이 시기를 노리라고 조언하고,
			이 시기가 좋은 이유를 간략히 설명하세요.

			""");

		prompt.append("""
			**3순위 타이밍** - 202X년 X월
			마지막 기회라는 점을 강조하고,
			이것마저 놓치면 어떻게 되는지 경고하세요.

			""");

		prompt.append("""
			**데드라인** - 202X년 X월 이후
			이 시기가 지나면 두 사람의 운이 완전히 엇갈린다는 점을 명확히 하고,
			특히 %s님에게 새로운 인연이 본격적으로 들어오기 시작해서
			재회 가능성이 거의 0퍼센트에 가까워진다는 점을 강조하세요.

			"""
			.formatted(person2Name));

		prompt.append("""
			**왜 이 시기들인지 사주 근거를 설명하세요**
			- 두 사람의 대운/세운 흐름 비교
			- 오행 조화 시기 (상생 vs 상극)
			- 신살 작용 (도화살, 역마살 등)
			전문 용어보다는 쉬운 말로 풀어서 설명하세요.

			""");

		// ==========================================
		// 제4장: 재회 실전 매뉴얼
		// ==========================================
		prompt.append("""
			==================================================
			📱 제4장: 재회 실전 매뉴얼
			==================================================

			""");

		prompt.append("""
			자, 이제 가장 중요한 파트입니다.
			이론은 그만하고, 실제로 어떻게 행동해야 하는지 알려드릴게요.

			""");

		prompt.append("""
			**재회 전 준비 단계** (최소 300자)

			""");

		prompt.append("""
			연락하기 전에 반드시 해야 할 일들을 구체적으로 제시하세요:

			""");

		prompt.append("""
			첫째, 당신 자신부터 바꿔야 합니다.
			%s님이 가장 먼저 고쳐야 할 점을 사주 약점 기반으로 지적하세요.
			예를 들어 의심과 집착, SNS 스토킹, 즉각적인 답장 요구 등
			구체적인 개선 포인트를 제시하고,
			이거 안 고치면 재회해도 100퍼센트 또 헤어진다고 경고하세요.

			"""
			.formatted(person1Name));

		prompt.append("""
			둘째, SNS 전략을 제시하세요.
			- 잘 지내는 모습을 보여주되 과하게 행복한 척하면 역효과
			- 적당히 성장한 모습을 보여주는 게 포인트
			- 상대방이 관심 가질 만한 콘텐츠 제안

			""");

		prompt.append("""
			셋째, 공통 지인 활용 전략이 있다면 제시하세요.

			""");

		prompt.append("""
			**첫 연락 대화 전략** (핵심! 최소 500자)

			""");

		prompt.append("""
			골든타임이 왔다고 가정하고, 첫 연락을 어떻게 보낼지 제시하세요.

			""");

		prompt.append("""
			%s님의 성격 분석을 바탕으로 맞춤 전략을 짜세요.

			"""
			.formatted(person2Name));

		prompt.append("""
			중요: Case 1, Case 2, Case 3 형식으로 나누지 말고,
			상대방의 사주 성향에 따라 자연스럽게 서술하세요.

			""");

		prompt.append("""
			예를 들어:
			- 상대방이 통제받기 싫어하는 타입이라면 가벼운 접근이 좋다고 설명하고
			- 절대 하면 안 되는 멘트와 추천 멘트를 각각 제시하세요
			- 상대방이 챙김받고 싶어하는 타입이라면 따뜻한 관심 표현이 좋다고 설명하고
			- 구체적인 예시를 들어주세요
			- 상대방이 자존심 강한 타입이라면 먼저 사과하는 게 필수라고 강조하세요

			""");

		prompt.append("""
			첫 연락 예시를 최소 3개 이상 제시하되,
			옵션 1, 옵션 2 형식보다는 흐름 있는 서술로 자연스럽게 풀어내세요.

			""");

		prompt.append("""
			**상대방 반응별 대처법을 시뮬레이션하세요**

			""");

		prompt.append("""
			호의적 반응이 오면:
			- 바로 만남을 제안하지 말고 2-3일 가벼운 대화 이어가기
			- 자연스럽게 밥 약속으로 연결하는 방법

			""");

		prompt.append("""
			중립 반응이 오면:
			- 아직 마음이 안 풀린 상태
			- 조금 더 기다리면서 가끔 안부만 전하기
			- 1-2주 후에 다시 시도하는 전략

			""");

		prompt.append("""
			냉담 반응이 오면:
			- 지금은 때가 아니라는 점 인정하기
			- 최소 1개월 이상 기다린 후 2순위 타이밍에 재도전하기
			- 절대 하면 안 되는 행동 (추가 메시지 폭탄, 전화, 장문의 사과문 등)

			""");

		prompt.append("""
			**만남 성사 후 행동 지침** (최소 400자)

			""");

		prompt.append("""
			드디어 만나게 됐을 때 어떻게 행동해야 하는지 구체적으로 제시하세요.

			""");

		prompt.append("""
			- %s님 사주상 가장 싫어하는 행동을 구체적으로 지적하세요

			"""
			.formatted(person2Name));

		prompt.append("""
			플러스 포인트 행동:
			- 옛날에 좋아했던 음식 기억해서 주문하기
			- 예전 추억 중 좋았던 순간만 언급하기
			- 변한 모습을 자연스럽게 보여주기

			""");

		prompt.append("""
			**재회 후 지속 전략** (재발 방지)

			""");

		prompt.append("""
			방심하면 똑같은 이유로 3개월 안에 또 헤어집니다.

			""");

		prompt.append("""
			근본 원인 해결 방법:
			제1장에서 분석한 헤어진 이유를 요약하고,
			이걸 해결하지 않으면 100퍼센트 재발한다고 경고하세요.

			""");

		prompt.append("""
			구체적 실천 방안:
			1. %s님이 해야 할 일을 구체적으로 제시하세요
			   예: 의심하는 습관 줄이기, 답장 늦어도 3시간은 참기, SNS 안 뒤지기

			"""
			.formatted(person1Name));

		prompt.append("""
			2. %s님에게 부탁해야 할 일을 제시하세요
			   예: 연락 조금만 더 자주 해주기
			   설득 멘트도 함께 제공하세요

			"""
			.formatted(person2Name));

		prompt.append("""
			위기 대처 매뉴얼:
			재회 후 다시 싸울 때 (반드시 올 겁니다):
			1단계: 일단 물리적으로 떨어지기
			2단계: 최소 2시간 쿨타임
			3단계: 먼저 미안해로 시작
			4단계: 감정이 아니라 사실만 이야기하기

			""");

		// ==========================================
		// 출력 형식 꼬리
		// ==========================================
		PromptSections.appendCompatibilityOutputFormat(prompt);

		// ==========================================
		// 최종 체크리스트
		// ==========================================
		prompt.append("""

			==================================================
			⚡ [최종 체크리스트 - 제출 전 필수 확인] ⚡
			==================================================

			""");

		prompt.append("""
			제출하기 전에 반드시 확인하세요:

			""");

		prompt.append("""
			✅ 전체 분량이 5000자 이상인가요?
			✅ 제1장(헤어진 이유)이 1500자 이상인가요?
			✅ 갈등 장면을 대본 형식이 아니라 간접화법으로 자연스럽게 서술했나요?
			✅ 작은따옴표를 과다하게 사용하지 않았나요?
			✅ Case 1/2/3 같은 획일적인 구조가 아니라 자연스러운 흐름인가요?
			✅ 재회 가능성을 별점(★)으로 명확히 평가했나요?
			✅ 타이밍 3개를 구체적 년/월로 제시했나요? (과거 날짜 없는지 확인!)
			✅ 첫 연락 예시를 최소 3개 이상 제시했나요?
			✅ 상대방 반응별 대처법을 시뮬레이션했나요?
			✅ 만남 후 금지 행동과 플러스 행동을 구분해서 제시했나요?
			✅ 재회 후 재발 방지 구체적 실천 방안을 제시했나요?
			✅ 사주 데이터에 기반한 고유한 분석인가요? (템플릿 같지 않은지)
			✅ 내담자가 와 이거 돈값 한다고 느낄 만한 디테일인가요?

			""");

		prompt.append("""
			이 모든 항목을 만족해야 제출할 수 있습니다.
			==================================================
			""");
	}
}
